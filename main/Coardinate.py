def get_real_coords(u, v, H):
    # Параметры сенсора и изображения
    W_p, H_p = 3280, 2464      # Разрешение в пикселях
    W_s, H_s = 3.67, 2.76      # Физический размер сенсора (мм)
    f = 2.96                   # Фокусное расстояние (мм)

    # 1. Находим центр изображения
    u_center = W_p / 2
    v_center = H_p / 2

    # 2. Вычисляем GSD (размер одного пикселя на объекте)
    # Формула: (H * размер_сенсора) / (f * разрешение)
    gsd_x = (H * W_s) / (f * W_p)
    gsd_y = (H * H_s) / (f * H_p)

    # 3. Считаем смещение от центра в пикселях
    delta_u = u - u_center
    delta_v = v_center - v  # Инвертируем v, чтобы Y рос "вверх" от центра

    # 4. Переводим пиксели в метрические единицы
    x_real = delta_u * gsd_x
    y_real = delta_v * gsd_y

    return round(x_real, 2), round(y_real, 2)

# Пример использования:
# Если объект в центре кадра (1640, 1232) на высоте 1000 мм:

print(get_real_coords(1640, 1232, 1000)) # Результат: (0.0, 0.0)

# Если объект смещен к краю (например, точка 2000, 500) на высоте 1000 мм:
x, y = get_real_coords(2000, 500, 1000)
print(f"Координаты объекта: X = {x} мм, Y = {y} мм")